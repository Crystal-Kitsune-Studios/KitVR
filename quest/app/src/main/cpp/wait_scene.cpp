GLuint buildSpriteTexture() {
    constexpr int kSize = 256;
    constexpr int kPixels = kSize * kSize;
    std::vector<unsigned char> pixels(static_cast<std::size_t>(kPixels) * 4, 0);
    auto slotOf = [](char c) {
        for (int i = 0; i < 64; ++i) {
            if (kSpriteAlphabet[i] == c) return i;
        }
        return 0;
    };
    int slot = 0;
    for (std::size_t i = 0; kSpriteRuns[i] && kSpriteRuns[i + 1]; i += 2) {
        int count = slotOf(kSpriteRuns[i]) + 1;
        int index = slotOf(kSpriteRuns[i + 1]);
        if (index < 0 || index > 15) index = 0;
        for (int n = 0; n < count && slot < kPixels; ++n, ++slot) {
            if (index == 0) continue;
            unsigned char* px = &pixels[static_cast<std::size_t>(slot) * 4];
            px[0] = kSpritePalette[index][0];
            px[1] = kSpritePalette[index][1];
            px[2] = kSpritePalette[index][2];
            px[3] = 255;
        }
    }
    GLuint texture = 0;
    glGenTextures(1, &texture);
    glBindTexture(GL_TEXTURE_2D, texture);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, kSize, kSize, 0, GL_RGBA,
                 GL_UNSIGNED_BYTE, pixels.data());
    glGenerateMipmap(GL_TEXTURE_2D);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR_MIPMAP_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, 0);
    return texture;
}

GLuint compileShader(GLenum type, const char* source) {
    GLuint shader = glCreateShader(type);
    glShaderSource(shader, 1, &source, nullptr);
    glCompileShader(shader);
    GLint ok = GL_FALSE;
    glGetShaderiv(shader, GL_COMPILE_STATUS, &ok);
    if (!ok) {
        char message[1024]{};
        glGetShaderInfoLog(shader, sizeof(message), nullptr, message);
        LOGE("waiting scene shader compilation failed: %s", message);
        glDeleteShader(shader);
        return 0;
    }
    return shader;
}

